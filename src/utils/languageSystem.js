const replaceKnownPhrases = (text) => {
    let translated = text;
    REPLACEMENT_ORDER.forEach((phrase) => {
        translated = translated.split(phrase).join(` ${TRANSLATION_GLOSSARY[phrase]} `);
    });
    return translated;
};

const normalizeEnglishPunctuation = (text) => text
    .replace(/：/gu, ': ')
    .replace(/，/gu, ', ')
    .replace(/。/gu, '.')
    .replace(/！/gu, '!')
    .replace(/？/gu, '?')
    .replace(/（/gu, '(')
    .replace(/）/gu, ')')
    .replace(/「/gu, '"')
    .replace(/」/gu, '"')
    .replace(/【/gu, '[')
    .replace(/】/gu, ']')
    .replace(/　/gu, ' ')
    .replace(/\s{2,}/gu, ' ')
    .trim();

const translateUnknownChinese = (match) => {
    const words = [];
    for (const char of match) {
        const translated = CHAR_TRANSLATIONS[char];
        if (translated === '') continue;
        if (translated) {
            words.push(translated);
        }
    }
    return words.join(' ');
};

const removeRemainingChinese = (text, original) => {
    if (!/[\p{Script=Han}]/u.test(text)) return text;

    return text.replace(/[\p{Script=Han}]+/gu, (match) => {
        if (TRANSLATION_GLOSSARY[match]) return TRANSLATION_GLOSSARY[match];
        if (/怪獸|寵物|牠|獸/.test(match)) return 'Monster';
        if (/技能|招式/.test(match)) return 'Skill';
        if (/物品|背包/.test(match)) return 'Item';
        if (/戰|勝|敗/.test(match)) return 'Battle';
        if (/雲|存|登入/.test(match)) return 'Cloud';
        return translateUnknownChinese(match);
    });
};

export const getStoredLanguage = () => {
    try {
        const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
        return stored === LANGUAGES.zh ? LANGUAGES.zh : LANGUAGES.en;
    } catch {
        return LANGUAGES.en;
    }
};

export const setStoredLanguage = (language) => {
    const nextLanguage = language === LANGUAGES.en ? LANGUAGES.en : LANGUAGES.zh;
    localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    window.dispatchEvent(new CustomEvent('pixel_monster_language_update', {
        detail: { language: nextLanguage },
    }));
};

export const translateText = (text, language = getStoredLanguage()) => {
    if (language !== LANGUAGES.en || typeof text !== 'string') return text;

    const leading = text.match(/^\s*/u)?.[0] || '';
    const trailing = text.match(/\s*$/u)?.[0] || '';
    let core = text.trim();
    if (!core) return text;

    if (EXACT_TRANSLATIONS[core]) {
        return `${leading}${EXACT_TRANSLATIONS[core]}${trailing}`;
    }

    for (const [pattern, replacement] of REGEX_TRANSLATIONS) {
        if (pattern.test(core)) {
            return `${leading}${core.replace(pattern, replacement)}${trailing}`;
        }
    }

    for (const [pattern, replacement] of PARTIAL_TRANSLATIONS) {
        if (pattern.test(core)) {
            core = core.replace(pattern, replacement);
            break;
        }
    }

    core = replaceKnownPhrases(core);
    core = normalizeEnglishPunctuation(core);
    core = removeRemainingChinese(core, text);

    return `${leading}${core}${trailing}`;
};

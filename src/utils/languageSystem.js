const toEnglishTitle = (id = '') => {
    const override = ENGLISH_NAME_OVERRIDES[id];
    if (override) return override;
    return String(id)
        .split(/[_-]+/u)
        .filter(Boolean)
        .map(part => part.charAt(0).toUpperCase() + part.slice(1))
        .join(' ');
};


import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CHAINS = [
  [10,11,12],[16,17,18],[29,30,31],[32,33,34],[43,44,45],[60,61,62],[63,64,65],[69,70,71],
  [81,82,462],[111,112,464],[440,113,242],[239,125,466],[240,126,467],
  [152,153,154],[155,156,157],[158,159,160],[179,180,181],[187,188,189],[220,221,473],[246,247,248],
  [255,256,257],[258,259,260],[270,271,272],[273,274,275],[287,288,289],[304,305,306],[328,329,330],
  [355,356,477],[371,372,373],[374,375,376],[387,388,389],[390,391,392],[393,394,395],[403,404,405]
];
const IDS = CHAINS.flat();
const API = 'https://pokeapi.co/api/v2';
const SPRITES = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-v/black-white';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'src', 'data', 'additionalThreeStagePokemonData.js');
const ASSET_ROOT = path.join(ROOT, 'public', 'assets', 'exclusive');
const fetchWithRetry = async (url, attempts = 5) => {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      const response = await fetch(url);
      if (response.ok) return response;
      lastError = new Error(`${response.status}: ${url}`);
    } catch (error) { lastError = error; }
    await new Promise(resolve => setTimeout(resolve, attempt * 500));
  }
  throw lastError;
};
const fetchJson = async url => (await fetchWithRetry(url)).json();
const mapLimit = async (items, limit, mapper) => { const out = new Array(items.length); let cursor = 0; await Promise.all(Array.from({ length: limit }, async () => { while (cursor < items.length) { const i = cursor++; out[i] = await mapper(items[i]); } })); return out; };
const localized = (entries, field = 'name') => entries.find(x => x.language?.name === 'zh-hant')?.[field] || entries.find(x => x.language?.name === 'en')?.[field] || '';
const clean = value => String(value || '').replace(/[\n\f\r]+/g, ' ').replace(/\s+/g, ' ').trim();
const download = async (url, destination) => { const response = await fetchWithRetry(url); await writeFile(destination, Buffer.from(await response.arrayBuffer())); };

const pokemon = await mapLimit(IDS, 8, async id => ({ mon: await fetchJson(`${API}/pokemon/${id}`), species: await fetchJson(`${API}/pokemon-species/${id}`) }));
const abilityNames = [...new Set(pokemon.flatMap(({ mon }) => mon.abilities.map(x => x.ability.name)))];
const abilities = await mapLimit(abilityNames, 8, name => fetchJson(`${API}/ability/${name}`));
const abilityDefinitions = Object.fromEntries(abilities.map(ability => {
  const flavor = [...ability.flavor_text_entries].reverse().find(x => x.language?.name === 'zh-hant') || [...ability.flavor_text_entries].reverse().find(x => x.language?.name === 'en');
  const text = clean(flavor?.flavor_text || '官方特性');
  return [ability.name, { id: ability.name, name: localized(ability.names) || ability.name, bonus: text, drawback: '無', bonusValue: text, drawbackValue: '無', modifiers: {}, implementation: { status: 'data_ready', notes: '官方特性資料；由共用戰鬥引擎依特性 ID 套用效果。' } }];
}));
const mappings = {};
const pools = {};
const englishNames = {};
for (const { mon, species } of pokemon) {
  const stat = name => mon.stats.find(x => x.stat.name === name)?.base_stat || 50;
  const zhName = localized(species.names) || mon.name;
  mappings[mon.id] = { pokemonId: mon.id, name: zhName, types: mon.types.sort((a,b) => a.slot-b.slot).map(x => x.type.name), baseStats: { hp: stat('hp'), atk: stat('attack'), def: stat('defense'), spd: stat('speed') } };
  pools[mon.id] = mon.abilities.sort((a,b) => a.slot-b.slot).map(x => x.ability.name);
  englishNames[zhName] = species.names.find(x => x.language?.name === 'en')?.name || mon.name;
}

for (const folder of ['idle', 'back', 'sprites']) await mkdir(path.join(ASSET_ROOT, folder), { recursive: true });
await mapLimit(IDS, 6, async id => {
  await Promise.all([
    download(`${SPRITES}/animated/${id}.gif`, path.join(ASSET_ROOT, 'idle', `${id}.gif`)),
    download(`${SPRITES}/animated/back/${id}.gif`, path.join(ASSET_ROOT, 'back', `${id}.gif`)),
    download(`${SPRITES}/${id}.png`, path.join(ASSET_ROOT, 'sprites', `${id}.png`)),
    download(`${SPRITES}/back/${id}.png`, path.join(ASSET_ROOT, 'back', `${id}.png`))
  ]);
});

const code = `// Generated by scripts/generate-additional-three-stage-pokemon.mjs from PokéAPI.\nexport const ADDITIONAL_THREE_STAGE_CHAINS = Object.freeze(${JSON.stringify(CHAINS)});\nexport const ADDITIONAL_THREE_STAGE_IDS = Object.freeze(${JSON.stringify(IDS)});\nexport const ADDITIONAL_THREE_STAGE_MAPPINGS = Object.freeze(${JSON.stringify(mappings, null, 2)});\nexport const ADDITIONAL_THREE_STAGE_ABILITY_DEFINITIONS = Object.freeze(${JSON.stringify(abilityDefinitions, null, 2)});\nexport const ADDITIONAL_THREE_STAGE_ABILITY_POOLS = Object.freeze(${JSON.stringify(pools, null, 2)});\nexport const ADDITIONAL_THREE_STAGE_ENGLISH_NAMES = Object.freeze(${JSON.stringify(englishNames, null, 2)});\n`;
await writeFile(OUTPUT, code, 'utf8');
console.log(`Generated ${CHAINS.length} complete chains (${IDS.length} Pokémon), ${abilities.length} abilities and four assets per Pokémon.`);
